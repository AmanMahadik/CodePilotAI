'use client';

import React, { useEffect, useState, Suspense } from 'react';
import { useParams, useSearchParams } from 'next/navigation';
import Link from 'next/link';
import { ShieldCheck, AlertTriangle, Loader2, ArrowLeft, Lock } from 'lucide-react';

interface VerifiedClaims {
  id: string;
  repo: string;
  branch: string;
  score: number;
  findingsCount: number;
  candidateName: string;
  referenceId: string;
  sha256: string;
  generatedAt: string;
}

function VerifyContent() {
  const params = useParams();
  const searchParams = useSearchParams();
  const reportId = (params?.id as string) || '';
  const token = searchParams.get('t') || '';

  const [loading, setLoading] = useState(true);
  const [valid, setValid] = useState(false);
  const [hashMatches, setHashMatches] = useState(false);
  const [claims, setClaims] = useState<VerifiedClaims | null>(null);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  useEffect(() => {
    const verify = async () => {
      try {
        const url = token
          ? `/api/reports/${encodeURIComponent(reportId)}/verify?t=${encodeURIComponent(token)}`
          : `/api/reports/${encodeURIComponent(reportId)}/verify`;
        const res = await fetch(url);
        const data = await res.json();
        if (res.ok && data.valid) {
          setValid(true);
          setHashMatches(Boolean(data.hashMatches));
          setClaims(data.claims || null);
        } else {
          setValid(false);
          setErrorMsg(data.error || 'Verification failed or token invalid.');
        }
      } catch {
        setValid(false);
        setErrorMsg('Unable to reach verification service.');
      } finally {
        setLoading(false);
      }
    };
    verify();
  }, [reportId, token]);

  if (loading) {
    return (
      <div className="min-h-[60vh] flex flex-col items-center justify-center gap-3 text-slate-300">
        <Loader2 className="w-8 h-8 animate-spin text-blue-500" />
        <span className="text-xs font-mono">Verifying cryptographic SHA-256 report digest...</span>
      </div>
    );
  }

  return (
    <div className="max-w-xl mx-auto py-8 px-4">
      <div className="rounded-2xl bg-[#0e1424] border border-[#1c2438] p-6 sm:p-8 shadow-2xl space-y-6">
        {valid && hashMatches && claims ? (
          <>
            <div className="flex items-center gap-3">
              <div className="w-12 h-12 rounded-xl bg-emerald-500/15 border border-emerald-500/30 text-emerald-400 flex items-center justify-center shrink-0">
                <ShieldCheck className="w-6 h-6" />
              </div>
              <div>
                <div className="text-xs font-mono text-emerald-400 uppercase tracking-wider">
                  Authentic &amp; Verified
                </div>
                <h1 className="text-xl font-bold text-white">CodePilot AI Audit Certificate</h1>
              </div>
            </div>

            <p className="text-xs text-slate-300 leading-relaxed">
              The cryptographic HMAC signature and SHA-256 payload digest match the sealed audit record generated by CodePilot AI.
            </p>

            <div className="p-4 rounded-xl bg-[#070a12] border border-[#172033] space-y-2.5 text-xs">
              <div className="flex justify-between gap-4">
                <span className="text-slate-400">Repository</span>
                <span className="text-white font-semibold">{claims.repo} ({claims.branch})</span>
              </div>
              <div className="flex justify-between gap-4">
                <span className="text-slate-400">Candidate / Author</span>
                <span className="text-white font-semibold">{claims.candidateName}</span>
              </div>
              <div className="flex justify-between gap-4">
                <span className="text-slate-400">Report Reference ID</span>
                <span className="font-mono text-blue-400">{claims.referenceId}</span>
              </div>
              <div className="flex justify-between gap-4">
                <span className="text-slate-400">Overall Health Score</span>
                <span className="font-bold text-emerald-400">{claims.score} / 100</span>
              </div>
              <div className="flex justify-between gap-4">
                <span className="text-slate-400">Recorded Findings</span>
                <span className="text-white font-mono">{claims.findingsCount}</span>
              </div>
              <div className="flex justify-between gap-4">
                <span className="text-slate-400">Issued At (UTC)</span>
                <span className="font-mono text-slate-300">{claims.generatedAt}</span>
              </div>
              <div className="pt-2 border-t border-[#172033]">
                <div className="text-[11px] text-slate-400 mb-1">SHA-256 Digest</div>
                <div className="font-mono text-[11px] text-emerald-400 break-all">{claims.sha256}</div>
              </div>
            </div>
          </>
        ) : (
          <div className="text-center space-y-4 py-4">
            <div className="w-12 h-12 rounded-xl bg-red-500/15 border border-red-500/30 text-red-400 flex items-center justify-center mx-auto">
              <AlertTriangle className="w-6 h-6" />
            </div>
            <h1 className="text-lg font-bold text-white">Report Verification Failed</h1>
            <p className="text-xs text-slate-400 leading-relaxed">{errorMsg}</p>
          </div>
        )}

        <div className="flex items-center justify-between pt-2 border-t border-[#1c2438] text-xs">
          <span className="flex items-center gap-1.5 text-slate-500">
            <Lock className="w-3.5 h-3.5" /> Read-only verification endpoint
          </span>
          <Link href="/auth/login" className="inline-flex items-center gap-1 text-blue-400 hover:underline">
            <ArrowLeft className="w-3.5 h-3.5" /> CodePilot AI Login
          </Link>
        </div>
      </div>
    </div>
  );
}

export default function VerifyReportPage() {
  return (
    <Suspense
      fallback={
        <div className="min-h-[60vh] flex items-center justify-center">
          <Loader2 className="w-6 h-6 animate-spin text-blue-500" />
        </div>
      }
    >
      <VerifyContent />
    </Suspense>
  );
}
