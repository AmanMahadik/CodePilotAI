'use client';

import React, { useState, useEffect } from 'react';
import Link from 'next/link';
import { BookOpen, Check, Copy, Download, RefreshCw, FileText, FolderGit2 } from 'lucide-react';
import { getLatestReview, getStoredRepositories } from '@/lib/store';
import { Review, Repository } from '@/lib/types';

export default function DocumentationPage() {
  const [activeTab, setActiveTab] = useState<'preview' | 'raw'>('preview');
  const [acceptedActions, setAcceptedActions] = useState<Record<string, boolean>>({});
  const [review, setReview] = useState<Review | null>(null);
  const [repo, setRepo] = useState<Repository | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    if (typeof window !== 'undefined') {
      const latest = getLatestReview();
      const repos = getStoredRepositories();
      setReview(latest || null);
      if (repos.length > 0) {
        setRepo(repos[0]);
      }
      setLoading(false);
    }
  }, []);

  const handleAccept = (file: string) => {
    setAcceptedActions((prev) => ({ ...prev, [file]: true }));
  };

  if (loading) {
    return (
      <div className="flex flex-col items-center justify-center min-h-[400px] text-slate-400">
        <div className="w-8 h-8 border-2 border-indigo-500 border-t-transparent rounded-full animate-spin mb-4" />
        <p className="text-sm font-mono">Loading documentation engine...</p>
      </div>
    );
  }

  const repoTitle = review?.repositoryName || repo?.name || '';

  if (!repoTitle) {
    return (
      <div className="max-w-4xl mx-auto py-12 px-4 text-center">
        <div className="w-16 h-16 rounded-2xl bg-indigo-500/10 border border-indigo-500/20 text-indigo-400 flex items-center justify-center mx-auto mb-4">
          <BookOpen className="w-8 h-8" />
        </div>
        <h2 className="text-xl font-bold text-white mb-2">No Repository Documentation Available</h2>
        <p className="text-sm text-slate-400 max-w-md mx-auto mb-6">
          Connect a repository and dispatch an analysis to auto-generate markdown documentation, architectural specs, and JSDoc contracts.
        </p>
        <Link
          href="/review/new"
          className="inline-flex items-center gap-2 px-4 py-2 rounded-lg bg-[#238636] hover:bg-[#2ea043] text-white text-xs font-semibold shadow-sm transition-colors"
        >
          <BookOpen className="w-4 h-4" />
          <span>Connect repository</span>
        </Link>
      </div>
    );
  }

  const rawMarkdown = review?.readmeDraft || `# ${repoTitle}

Automated documentation generated by CodePilot Documentation Agent.

[![Build](https://img.shields.io/badge/build-passing-brightgreen)]()
[![CodePilot Score](https://img.shields.io/badge/CodePilot%20Score-${review?.scores.overall || 90}%2F100-blue)]()

## Overview
Comprehensive software project index for **${repoTitle}**. Multi-agent pipeline parsed ${review?.totalFilesAnalyzed || 1} files (${review?.totalLinesOfCode || 100} LOC) on branch \`${review?.branch || 'main'}\`.

## Architecture
\`\`\`
Client / Presentation Layer
  ↓
API Route Handlers & Controllers
  ↓
Domain Services & Business Logic
  ↓
Data Persistence Layer
\`\`\`

## Getting Started
\`\`\`bash
# Install dependencies
npm install

# Run development server
npm run dev

# Run test suite
npm test
\`\`\`

## Quality & Security Audit
- Overall Code Health: ${review?.scores.overall || 90}/100
- OWASP Security Score: ${review?.scores.security || 85}%
- Code Quality Rating: ${review?.scores.quality || 88}%
- Reliability Index: ${review?.scores.reliability || 88}%
`;

  // Doc suggestions from review or findings
  const docSuggestions = (review?.inlineDocSuggestions && review.inlineDocSuggestions.length > 0)
    ? review.inlineDocSuggestions
    : (review?.findings || [])
        .filter((f) => f.agentType === 'documentation' || f.category === 'documentation')
        .map((f, i) => ({
          file: f.file,
          functionName: f.title,
          line: f.lineStart,
          suggestedDoc: f.suggestedFix || f.principleExplanation || 'Add parameter definitions and type signatures.',
        }));

  return (
    <div className="space-y-6 max-w-5xl mx-auto">
      {/* Top Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between pb-2 gap-4">
        <div>
          <div className="text-[11px] font-mono text-slate-500 uppercase tracking-wider mb-1">
            {repoTitle.toUpperCase()} / DOCUMENTATION
          </div>
          <h1 className="text-2xl sm:text-3xl font-extrabold text-white tracking-tight">
            Documentation Agent
          </h1>
          <p className="text-xs text-slate-400 mt-0.5">
            Auto-generated architecture blueprints, README documentation, and docstring contracts.
          </p>
        </div>

        <button
          onClick={() => alert(`Documentation regenerated for ${repoTitle}.`)}
          className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-md bg-[#238636] hover:bg-[#2ea043] text-white text-xs font-semibold shadow-sm transition-colors shrink-0"
        >
          <BookOpen className="w-4 h-4" />
          <span>Regenerate docs</span>
        </button>
      </div>

      {/* Tabs */}
      <div className="flex border-b border-[#1c2438] gap-6 text-xs font-semibold">
        <button
          onClick={() => setActiveTab('preview')}
          className={`pb-2.5 transition-colors ${
            activeTab === 'preview'
              ? 'text-white border-b-2 border-[#f0883e]'
              : 'text-slate-400 hover:text-slate-200'
          }`}
        >
          Preview
        </button>
        <button
          onClick={() => setActiveTab('raw')}
          className={`pb-2.5 transition-colors ${
            activeTab === 'raw'
              ? 'text-white border-b-2 border-[#f0883e]'
              : 'text-slate-400 hover:text-slate-200'
          }`}
        >
          Raw Markdown
        </button>
      </div>

      {/* Main Documentation Card */}
      <div className="rounded-xl bg-[#0e1424] border border-[#1c2438] p-6 space-y-6">
        {activeTab === 'preview' ? (
          <div className="space-y-6 text-xs">
            {/* Header Badge */}
            <div className="flex items-center justify-between pb-3 border-b border-[#1c2438]">
              <span className="px-2.5 py-0.5 rounded-full bg-[#238636]/15 border border-[#238636]/40 text-[#3fb950] font-mono font-bold text-[10px]">
                README.md • Dynamic Agent Output
              </span>
              <span className="text-[10px] font-mono text-slate-500">Updated for {repoTitle}</span>
            </div>

            {/* Title & Description */}
            <div>
              <h2 className="text-xl font-extrabold text-white">{repoTitle}</h2>
              <p className="text-slate-400 mt-1">
                Centralized architectural summary and developer reference.
              </p>
            </div>

            {/* Badges */}
            <div className="flex flex-wrap items-center gap-2 font-mono text-[10px]">
              <span className="px-2 py-0.5 rounded bg-[#238636] text-white font-bold">
                build passing
              </span>
              <span className="px-2 py-0.5 rounded bg-[#161f33] text-slate-300 border border-[#22304d]">
                Health Score: {review?.scores.overall || 90}/100
              </span>
              <span className="px-2 py-0.5 rounded bg-[#161f33] text-slate-300 border border-[#22304d]">
                Branch: {review?.branch || 'main'}
              </span>
            </div>

            {/* Section: Overview */}
            <div>
              <h3 className="text-sm font-bold text-white mb-1.5">Overview</h3>
              <p className="text-slate-300 leading-relaxed">
                Repository {repoTitle} parsed across {review?.totalFilesAnalyzed || 1} files ({review?.totalLinesOfCode || 100} lines of code). The multi-agent pipeline confirmed modular structure, consistent layering, and clean encapsulation boundaries.
              </p>
            </div>

            {/* Section: Architecture */}
            <div>
              <h3 className="text-sm font-bold text-white mb-1.5">Architecture Diagram</h3>
              <pre className="p-4 rounded-lg bg-[#070a12] border border-[#172033] font-mono text-[11px] text-[#58a6ff] leading-relaxed">
{`Client Applications / Consumers
  ↓
API Gateway & Route Handlers
  ↓
Domain Logic & Core Processing
  ↓
Storage, Database & Cache Systems`}
              </pre>
            </div>

            {/* Section: Getting Started */}
            <div>
              <h3 className="text-sm font-bold text-white mb-1.5">Getting Started</h3>
              <div className="p-3.5 rounded-lg bg-[#070a12] border border-[#172033] font-mono text-[11px] text-[#3fb950] space-y-1">
                <div>npm install</div>
                <div>npm run dev</div>
              </div>
            </div>
          </div>
        ) : (
          <textarea
            readOnly
            value={rawMarkdown}
            rows={18}
            className="w-full p-4 rounded-lg bg-[#070a12] border border-[#172033] font-mono text-xs text-slate-300 leading-relaxed font-mono"
          />
        )}
      </div>

      {/* Inline JSDoc / Docstring Suggestions Table */}
      <div className="rounded-xl bg-[#0e1424] border border-[#1c2438] p-5 space-y-3">
        <h3 className="text-xs font-bold text-white font-mono uppercase tracking-wider">
          Inline JSDoc / Docstring suggestions
        </h3>

        {docSuggestions.length === 0 ? (
          <p className="text-xs text-slate-400">
            No undocumented functions flagged. Public exports meet documented interface requirements.
          </p>
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full text-left text-xs">
              <thead>
                <tr className="text-[10px] font-mono text-slate-400 border-b border-[#1c2438]">
                  <th className="pb-2 font-semibold">FILE</th>
                  <th className="pb-2 font-semibold">SUGGESTION</th>
                  <th className="pb-2 font-semibold text-right">ACTION</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-[#172033] font-mono">
                {docSuggestions.map((item, i) => {
                  const key = `${item.file}-${i}`;
                  const isAccepted = acceptedActions[key];
                  return (
                    <tr key={key} className="hover:bg-[#131b2e] transition-colors">
                      <td className="py-3 text-[#58a6ff] font-bold">{item.file}</td>
                      <td className="py-3 text-slate-300 font-sans">
                        {item.suggestedDoc || item.functionName}
                      </td>
                      <td className="py-3 text-right">
                        <button
                          onClick={() => handleAccept(key)}
                          className={`px-3 py-1 rounded text-xs font-sans transition-colors ${
                            isAccepted
                              ? 'bg-[#238636]/20 text-[#3fb950] border border-[#238636]/40 cursor-default'
                              : 'bg-[#161f33] hover:bg-[#1f2c49] text-slate-200 border border-[#22304d]'
                          }`}
                        >
                          {isAccepted ? 'Accepted' : 'Accept'}
                        </button>
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </div>
  );
}
